for lang in languages:
    filepath = os.path.join(locales_dir, f"{lang}.json")
    with open(filepath, "r", encoding="utf-8") as f:
        content = json.load(f)

    for section, keys in steps_translations.items():
        if section not in content:
            content[section] = {}
        for key_name, lang_dict in keys.items():
            content[section][key_name] = lang_dict.get(lang, lang_dict["en"])

    with open(filepath, "w", encoding="utf-8") as f:
        json.dump(content, f, ensure_ascii=False, indent=2)

print("Step translations synchronized successfully across all 9 languages!")
